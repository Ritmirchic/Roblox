GLYPH_W, GLYPH_H = 5, 7


def glyph(ch: str):
    if ch in G:
        return G[ch]
    alt = ch.lower() if ch.isupper() else ch.upper()
    if alt in G:
        return G[alt]
    return G["?"]


def text_size(text: str, spacing: int = 1, scale: int = 1):
    lines = text.split("\n")
    w = max((len(l) * (GLYPH_W + spacing) - spacing) for l in lines) if lines else 0
    h = len(lines) * (GLYPH_H + 2) - 2
    return max(w, 0) * scale, max(h, 0) * scale


def draw_text(
    raster,
    x: int,
    y: int,
    text: str,
    color,
    spacing: int = 1,
    line_h: int | None = None,
    shadow=None,
    outline=None,
    scale: int = 1,
) -> tuple[int, int]:
    """Нарисовать текст. Возвращает (ширина, высота) блока в пикселях.

    shadow  — тень на 1px вниз-вправо (читаемость на пёстром фоне)
    outline — обводка 1px по контуру (для субтитров поверх сцены)

    Рисуется в два прохода: сначала весь контур/тень, потом заливка.
    Иначе контур следующей буквы затирает заливку предыдущей.
    """
    line_h = (GLYPH_H + 2) if line_h is None else line_h
    lines = text.split("\n")
    ink: list[tuple[int, int]] = []
    maxw = 0
    for li, line in enumerate(lines):
        cx = x
        for ch in line:
            g = glyph(ch)
            for gy, row in enumerate(g):
                for gx, c in enumerate(row):
                    if c == "#":
                        px = cx + gx * scale
                        py = y + li * line_h * scale + gy * scale
                        if scale == 1:
                            ink.append((px, py))
                        else:
                            for sy in range(scale):
                                for sx in range(scale):
                                    ink.append((px + sx, py + sy))
            cx += (GLYPH_W + spacing) * scale
        maxw = max(maxw, cx - x - spacing * scale)

    if outline is not None:
        for px, py in ink:
            for oy in (-1, 0, 1):
                for ox in (-1, 0, 1):
                    raster.put(px + ox, py + oy, outline)
    elif shadow is not None:
        for px, py in ink:
            raster.put(px + 1, py + 1, shadow)
    for px, py in ink:
        raster.put(px, py, color)
    return maxw, len(lines) * line_h * scale - 2 * scale


def wrap_text(text: str, max_px: int, spacing: int = 1, scale: int = 1) -> list[str]:
    """Перенос по словам под ширину в пикселях."""
    char_w = (GLYPH_W + spacing) * scale
    max_chars = max(1, (max_px + spacing * scale) // char_w)
    out: list[str] = []
    for para in text.split("\n"):
        cur = ""
        for word in para.split(" "):
            if not cur:
                cur = word
            elif len(cur) + 1 + len(word) <= max_chars:
                cur += " " + word
            else:
                out.append(cur)
                cur = word
        out.append(cur)
    return out
